import { spawnSync } from "node:child_process";
import { realpathSync } from "node:fs";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { ReadOnlyZonesConfigError } from "./errors.js";
import {
  checkTarget,
  findGitRoot,
  globToRegExp,
  loadZonesConfig,
  parseZonesConfig,
  runReadOnlyZonesHook,
  ZONES_CONFIG_PATH,
  type Zone,
} from "./read-only-zones.js";

let project: string;

async function write(rel: string, content: string): Promise<void> {
  const full = join(project, rel);
  await mkdir(dirname(full), { recursive: true });
  await writeFile(full, content);
}

async function writeZones(zones: readonly Zone[]): Promise<void> {
  await write(ZONES_CONFIG_PATH, JSON.stringify(zones));
}

const DIST_ZONE: Zone = { glob: "plugins/*/dist/**", why: "generated by pnpm build" };

const neverRead = (): Promise<string> =>
  Promise.reject(new Error("stdin was read before the config check"));

function event(toolName: string, toolInput: Record<string, unknown>, cwd = project): string {
  return JSON.stringify({ hook_event_name: "PreToolUse", tool_name: toolName, tool_input: toolInput, cwd });
}

beforeEach(async () => {
  project = await mkdtemp(join(tmpdir(), "read-only-zones-"));
  await mkdir(join(project, ".git"), { recursive: true });
});

afterEach(async () => {
  await rm(project, { recursive: true, force: true });
});

describe("globToRegExp", () => {
  it.each([
    ["dist/**", "dist/a/b.js", true],
    ["dist/**", "src/dist/a.js", false],
    ["**/dist/**", "plugins/x/dist/a.js", true],
    ["**/*.lock", "pnpm-lock.yaml", false],
    ["**/*.lock", "deep/yarn.lock", true],
    ["*.md", "README.md", true],
    ["*.md", "docs/README.md", false],
    ["src/?.ts", "src/a.ts", true],
    ["src/?.ts", "src/ab.ts", false],
    ["*.{js,ts}", "a.ts", true],
    ["*.{js,ts}", "a.tsx", false],
    ["src/[ab].ts", "src/b.ts", true],
    ["src/[ab].ts", "src/c.ts", false],
    ["a.b", "axb", false],
    ["dist/", "dist/a.js", true],
    ["dist/", "dist", false],
    ["src/[!a].ts", "src/b.ts", true],
    ["src/[!a].ts", "src/a.ts", false],
  ])("%s against %s is %s", (glob, path, expected) => {
    expect(globToRegExp(glob).test(path)).toBe(expected);
  });
});

describe("parseZonesConfig", () => {
  it("accepts an array of glob and why entries", () => {
    expect(parseZonesConfig(JSON.stringify([DIST_ZONE]), "cfg")).toEqual([DIST_ZONE]);
  });

  it.each([
    ["{", "invalid JSON"],
    ["{}", "expected a JSON array"],
    ["[1]", "entry 0 is not an object"],
    ['[{"why":"x"}]', 'entry 0 needs a non-empty "glob" string'],
    ['[{"glob":"dist/**"}]', 'entry 0 ("dist/**") needs a non-empty "why" string'],
    ['[{"glob":"dist/**","why":"  "}]', 'needs a non-empty "why" string'],
  ])("rejects %s", (raw, detail) => {
    expect(() => parseZonesConfig(raw, "cfg")).toThrow(ReadOnlyZonesConfigError);
    expect(() => parseZonesConfig(raw, "cfg")).toThrow(detail);
    expect(() => parseZonesConfig(raw, "cfg")).toThrow("Fix the file by hand");
  });
});

describe("loadZonesConfig", () => {
  it("returns null when the project has no config", () => {
    expect(loadZonesConfig(project)).toBeNull();
  });

  it("appends the config file itself as an implicit zone", async () => {
    await writeZones([DIST_ZONE]);
    const zones = loadZonesConfig(project);
    expect(zones?.map((z) => z.glob)).toEqual([DIST_ZONE.glob, ZONES_CONFIG_PATH]);
  });

  it("names the file and the parse error when the config is malformed", async () => {
    await write(ZONES_CONFIG_PATH, "[{");
    expect(() => loadZonesConfig(project)).toThrow(join(project, ZONES_CONFIG_PATH));
    expect(() => loadZonesConfig(project)).toThrow("invalid JSON");
  });

  it("fails when the config path is a directory", async () => {
    await mkdir(join(project, ZONES_CONFIG_PATH), { recursive: true });
    expect(() => loadZonesConfig(project)).toThrow("cannot read it");
  });
});

describe("findGitRoot", () => {
  it("finds a .git directory above a nested path", async () => {
    await mkdir(join(project, "a/b"), { recursive: true });
    expect(findGitRoot(join(project, "a/b"))).toBe(project);
  });

  it("finds a .git file, as linked worktrees have", async () => {
    await write(".claude/worktrees/wt/.git", `gitdir: ${join(project, ".git/worktrees/wt")}\n`);
    await mkdir(join(project, ".claude/worktrees/wt/src"), { recursive: true });
    expect(findGitRoot(join(project, ".claude/worktrees/wt/src"))).toBe(
      join(project, ".claude/worktrees/wt"),
    );
  });

  it("returns null without any .git ancestor", async () => {
    const bare = await mkdtemp(join(tmpdir(), "no-git-"));
    try {
      expect(findGitRoot(bare)).toBeNull();
    } finally {
      await rm(bare, { recursive: true, force: true });
    }
  });
});

describe("checkTarget", () => {
  const zones = [DIST_ZONE];

  it("blocks a path inside a zone and reports it relative to the root", () => {
    const result = checkTarget({ projectDir: project, zones, targetPath: join(project, "plugins/x/dist/a.js") });
    expect(result).toEqual({ blocked: true, relativePath: "plugins/x/dist/a.js", zone: DIST_ZONE });
  });

  it("allows a path outside every zone", () => {
    expect(checkTarget({ projectDir: project, zones, targetPath: join(project, "plugins/x/src/a.ts") })).toEqual({
      blocked: false,
      reason: "no-match",
    });
  });

  it("normalises .. segments so they cannot escape a zone", () => {
    const sneaky = join(project, "plugins/x/src/../dist/a.js");
    expect(checkTarget({ projectDir: project, zones, targetPath: sneaky }).blocked).toBe(true);
  });

  it("matches relative to a linked worktree root inside the project", async () => {
    const wt = join(project, ".claude/worktrees/wt");
    await write(".claude/worktrees/wt/.git", `gitdir: ${join(project, ".git/worktrees/wt")}\n`);
    const result = checkTarget({ projectDir: project, zones, targetPath: join(wt, "plugins/x/dist/a.js") });
    expect(result).toMatchObject({ blocked: true, relativePath: "plugins/x/dist/a.js" });
  });

  it("matches a linked worktree outside the project when its .git points into the project", async () => {
    const wt = await mkdtemp(join(tmpdir(), "external-wt-"));
    try {
      await mkdir(join(project, ".git/worktrees/wt"), { recursive: true });
      await writeFile(join(wt, ".git"), `gitdir: ${join(project, ".git/worktrees/wt")}\n`);
      const result = checkTarget({ projectDir: project, zones, targetPath: join(wt, "plugins/x/dist/a.js") });
      expect(result).toMatchObject({ blocked: true, relativePath: "plugins/x/dist/a.js" });
    } finally {
      await rm(wt, { recursive: true, force: true });
    }
  });

  it("matches relative to the session directory when it sits inside a larger repository", async () => {
    const app = join(project, "packages/app");
    await write("packages/app/.claude/read-only-zones.json", JSON.stringify([{ glob: "dist/**", why: "built" }]));
    const appZones: Zone[] = [{ glob: "dist/**", why: "built" }];
    expect(checkTarget({ projectDir: app, zones: appZones, targetPath: join(app, "dist/a.js") })).toMatchObject({
      blocked: true,
      relativePath: "dist/a.js",
    });
    expect(checkTarget({ projectDir: app, zones: appZones, targetPath: join(project, "packages/other/dist/a.js") })).toEqual({
      blocked: false,
      reason: "outside-project",
    });
  });

  describe.each([
    ["a nested repo with a .git directory", () => mkdir(join(project, "vendor/lib/.git"), { recursive: true })],
    [
      "a submodule whose .git file points into .git/modules/",
      async () => {
        await mkdir(join(project, ".git/modules/vendor/lib"), { recursive: true });
        await write("vendor/lib/.git", "gitdir: ../../.git/modules/vendor/lib\n");
      },
    ],
  ])("inside %s", (_label, createNestedRepo) => {
    const vendorZone: Zone = { glob: "vendor/lib/**", why: "vendored" };
    const rootDistZone: Zone = { glob: "dist/**", why: "build output" };

    beforeEach(async () => {
      await createNestedRepo();
    });

    it("matches relative to the project root, so a zone naming the nested directory blocks it", () => {
      const nestedZones = [rootDistZone, vendorZone];
      expect(checkTarget({ projectDir: project, zones: nestedZones, targetPath: join(project, "vendor/lib/x.js") })).toEqual({
        blocked: true,
        relativePath: "vendor/lib/x.js",
        zone: vendorZone,
      });
      expect(checkTarget({ projectDir: project, zones: nestedZones, targetPath: join(project, "vendor/lib/dist/a.js") })).toEqual({
        blocked: true,
        relativePath: "vendor/lib/dist/a.js",
        zone: vendorZone,
      });
    });

    it("keeps a root-level zone off the nested repo's own directories", () => {
      expect(checkTarget({ projectDir: project, zones: [rootDistZone], targetPath: join(project, "vendor/lib/dist/a.js") })).toEqual({
        blocked: false,
        reason: "no-match",
      });
      expect(checkTarget({ projectDir: project, zones: [rootDistZone], targetPath: join(project, "dist/a.js") })).toMatchObject({
        blocked: true,
        relativePath: "dist/a.js",
      });
    });

    it("matches relative to the session directory when the session started above the nested repo", () => {
      const vendor = join(project, "vendor");
      const libZone: Zone = { glob: "lib/dist/**", why: "built" };
      expect(checkTarget({ projectDir: vendor, zones: [libZone], targetPath: join(vendor, "lib/dist/a.js") })).toMatchObject({
        blocked: true,
        relativePath: "lib/dist/a.js",
      });
    });
  });

  it("compares the project and the target through their real paths", () => {
    const result = checkTarget({ projectDir: realpathSync(project), zones, targetPath: join(project, "plugins/x/dist/a.js") });
    expect(result).toMatchObject({ blocked: true, relativePath: "plugins/x/dist/a.js" });
  });

  it.runIf(process.platform === "darwin" || process.platform === "win32")("folds case on case-insensitive platforms", () => {
    expect(checkTarget({ projectDir: project, zones, targetPath: join(project, "plugins/x/DIST/a.js") }).blocked).toBe(true);
  });

  it("allows a target in another repository", async () => {
    const other = await mkdtemp(join(tmpdir(), "other-repo-"));
    try {
      await mkdir(join(other, ".git"), { recursive: true });
      const result = checkTarget({ projectDir: project, zones, targetPath: join(other, "plugins/x/dist/a.js") });
      expect(result).toEqual({ blocked: false, reason: "outside-project" });
    } finally {
      await rm(other, { recursive: true, force: true });
    }
  });

  it("allows a target with no .git ancestor", async () => {
    const bare = await mkdtemp(join(tmpdir(), "no-git-"));
    try {
      const result = checkTarget({ projectDir: project, zones, targetPath: join(bare, "plugins/x/dist/a.js") });
      expect(result).toEqual({ blocked: false, reason: "no-root" });
    } finally {
      await rm(bare, { recursive: true, force: true });
    }
  });
});

describe("runReadOnlyZonesHook", () => {
  it("exits 0 without reading stdin when CLAUDE_PROJECT_DIR is unset", async () => {
    await expect(runReadOnlyZonesHook({ projectDir: undefined, readStdin: neverRead })).resolves.toEqual({
      exitCode: 0,
      message: null,
    });
  });

  it("exits 0 without reading stdin when the project has no config", async () => {
    await expect(runReadOnlyZonesHook({ projectDir: project, readStdin: neverRead })).resolves.toEqual({
      exitCode: 0,
      message: null,
    });
  });

  it("exits 2 naming the file and the parse error when the config is malformed", async () => {
    await write(ZONES_CONFIG_PATH, '[{"glob": "dist/**"}]');
    const outcome = await runReadOnlyZonesHook({ projectDir: project, readStdin: neverRead });
    expect(outcome.exitCode).toBe(2);
    expect(outcome.message).toContain(join(project, ZONES_CONFIG_PATH));
    expect(outcome.message).toContain('needs a non-empty "why" string');
    expect(outcome.message).toContain("Fix the file by hand");
  });

  it("exits 2 when stdin is not JSON and a config exists", async () => {
    await writeZones([DIST_ZONE]);
    const outcome = await runReadOnlyZonesHook({ projectDir: project, readStdin: async () => "not json" });
    expect(outcome.exitCode).toBe(2);
    expect(outcome.message).toContain("cannot parse the hook input");
  });

  it("blocks an Edit inside a zone with the path and the why", async () => {
    await writeZones([DIST_ZONE]);
    const outcome = await runReadOnlyZonesHook({
      projectDir: project,
      readStdin: async () => event("Edit", { file_path: join(project, "plugins/x/dist/a.js"), old_string: "a", new_string: "b" }),
    });
    expect(outcome.exitCode).toBe(2);
    expect(outcome.message).toContain("plugins/x/dist/a.js");
    expect(outcome.message).toContain(DIST_ZONE.why);
  });

  it("reads notebook_path for NotebookEdit", async () => {
    await writeZones([{ glob: "notebooks/**", why: "published analyses" }]);
    const outcome = await runReadOnlyZonesHook({
      projectDir: project,
      readStdin: async () => event("NotebookEdit", { notebook_path: join(project, "notebooks/a.ipynb"), new_source: "" }),
    });
    expect(outcome).toMatchObject({ exitCode: 2 });
    expect(outcome.message).toContain("notebooks/a.ipynb");
  });

  it("ignores the stdin cwd when the target is absolute", async () => {
    await writeZones([DIST_ZONE]);
    const subdir = join(project, "plugins/x/src");
    await mkdir(subdir, { recursive: true });
    const blocked = await runReadOnlyZonesHook({
      projectDir: project,
      readStdin: async () => event("Write", { file_path: join(project, "plugins/x/dist/a.js"), content: "" }, subdir),
    });
    expect(blocked.exitCode).toBe(2);
    const allowed = await runReadOnlyZonesHook({
      projectDir: project,
      readStdin: async () => event("Write", { file_path: join(subdir, "a.ts"), content: "" }, subdir),
    });
    expect(allowed).toEqual({ exitCode: 0, message: null });
  });

  it("resolves a relative target against the stdin cwd", async () => {
    await writeZones([DIST_ZONE]);
    const outcome = await runReadOnlyZonesHook({
      projectDir: project,
      readStdin: async () => event("Write", { file_path: "dist/a.js", content: "" }, join(project, "plugins/x")),
    });
    expect(outcome.exitCode).toBe(2);
  });

  it("blocks edits to the config file itself", async () => {
    await writeZones([]);
    const outcome = await runReadOnlyZonesHook({
      projectDir: project,
      readStdin: async () => event("Edit", { file_path: join(project, ZONES_CONFIG_PATH) }),
    });
    expect(outcome.exitCode).toBe(2);
    expect(outcome.message).toContain("edited by hand");
  });

  it("exits 0 for a tool input without a path", async () => {
    await writeZones([DIST_ZONE]);
    const outcome = await runReadOnlyZonesHook({ projectDir: project, readStdin: async () => event("Edit", {}) });
    expect(outcome).toEqual({ exitCode: 0, message: null });
  });
});

// The compiled hook is what users run; this checks the wiring end to end.
// Run `pnpm build` first or it tests stale code.
describe("compiled hook", () => {
  const pluginRoot = new URL("../../", import.meta.url).pathname;
  const hookBin = join(pluginRoot, "dist/bin/read-only-zones-hook.js");

  function runHook(env: Record<string, string>, stdin: string) {
    return spawnSync(process.execPath, [hookBin], { env: { ...process.env, ...env }, input: stdin, encoding: "utf8" });
  }

  it("is the command hooks.json registers for Edit, Write and NotebookEdit", async () => {
    const hooks = JSON.parse(await readFile(join(pluginRoot, "hooks/hooks.json"), "utf8"));
    const [entry] = hooks.hooks.PreToolUse;
    expect(entry.matcher).toBe("Edit|Write|NotebookEdit");
    expect(entry.hooks[0].command).toBe('node "${CLAUDE_PLUGIN_ROOT}/dist/bin/read-only-zones-hook.js"');
  });

  it("exits 2 with the reason on stderr for a zone hit, 0 otherwise", async () => {
    await writeZones([DIST_ZONE]);
    const hit = runHook({ CLAUDE_PROJECT_DIR: project }, event("Edit", { file_path: join(project, "plugins/x/dist/a.js") }));
    expect(hit.status).toBe(2);
    expect(hit.stderr).toContain(DIST_ZONE.why);
    const miss = runHook({ CLAUDE_PROJECT_DIR: project }, event("Edit", { file_path: join(project, "plugins/x/src/a.ts") }));
    expect(miss.status).toBe(0);
    expect(miss.stderr).toBe("");
  });
});
